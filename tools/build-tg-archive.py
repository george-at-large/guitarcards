#!/usr/bin/env python3
"""Build content/tgarchive.js: one lesson card per PDF in the Ted Greene archive index.
Only titles, topics, dates and the public tedgreene.com links are stored (no lesson content).
usage: python3 tools/build-tg-archive.py "/Users/.../Ted Greene Lessons/Download index.csv"
"""
import csv, json, re, sys, os

LEVEL = {'Fundamentals': 3, 'Blues': 4, 'Chord Studies': 5, 'Comping': 5, 'Harmony and Theory': 5, 'Single Note Soloing': 5,
         'Jazz': 5, 'Other Lessons': 5, 'From Students': 5, 'Recorded Lesson Supplements': 5, 'The V-System': 6, 'Baroque': 6,
         'Arrangements': 7, 'Transcriptions': 7}

def title_of(path):
    name = os.path.splitext(os.path.basename(path))[0]
    date = None
    m = re.search(r'(19|20)\d\d(-\d\d(-\d\d)?)?', name)
    if m: date = m.group(0)
    t = re.sub(r'[_-]?(19|20)\d\d(-\d\d)*(_\d\d)*', ' ', name)
    t = re.sub(r'(?i)[_ -]*(ted ?greene|tg)(s)?(arrangement|arr|leadsheet|lead ?sheet|comping|pianoarrangement)?(?=[_\W]|$)', ' ', t)
    t = re.sub(r'(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])|(?<=[A-Za-z])(?=\d)', ' ', t)
    t = re.sub(r'[_]+', ' ', t)
    t = re.sub(r'(?<!\bV)\s*-\s*(?!\d)|\s+-\s+', ' – ', t)
    t = re.sub(r'\s+', ' ', t).strip(' –-')
    return (t or name), date

def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')[:60]

def main(csv_path):
    rows = list(csv.DictReader(open(csv_path, newline='', encoding='utf-8')))
    lessons, templates, seen = [], [], set()
    for r in rows:
        if r.get('Status') != 'ok':
            continue
        cat = r['Category']
        title, date = title_of(r['File'])
        lid = 'tga-' + slug(cat)[:12] + '-' + slug(os.path.splitext(os.path.basename(r['File']))[0])
        while lid in seen: lid += '-x'
        seen.add(lid)
        lessons.append({'id': lid, 'cat': cat, 'title': title, 'date': date, 'url': r['Source URL'], 'file': r['File']})
        templates.append({
            'id': lid, 'mode': 'play', 'category': 'tedgreene', 'tags': ['ted-greene', 'tg-archive', slug(cat)],
            'title': f'Ted Greene lesson: {title}', 'level': LEVEL.get(cat, 5), 'length': 'long', 'minutes': 15,
            'prompt': f'Open Ted Greene\'s lesson sheet **{title}** ({cat}{", " + date if date else ""}) and work through it with the guitar: '
                      'play every example slowly, then pick one idea and use it in a tune. Rate how far you got.',
            'goal': 'One idea from the sheet you can play from memory.',
            'link': r['Source URL'],
            'source': f'Ted Greene lesson archive (tedgreene.com) — {cat}',
        })
    cats = {}
    for l in lessons: cats.setdefault(l['cat'], 0); cats[l['cat']] += 1
    out = os.path.join(os.path.dirname(__file__), '..', 'content', 'tgarchive.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/build-tg-archive.py — index only (titles + public tedgreene.com links).\n')
        f.write('export const tgArchive = ' + json.dumps({'folders': cats, 'lessons': lessons}, ensure_ascii=False) + ';\n')
        f.write('export const templates = ' + json.dumps(templates, ensure_ascii=False, indent=0) + ';\n')
    print(f'{len(lessons)} lessons in {len(cats)} folders -> content/tgarchive.js')

if __name__ == '__main__':
    main(sys.argv[1])
